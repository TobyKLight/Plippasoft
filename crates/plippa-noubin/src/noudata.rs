/// Noubin §3.1 minimal playable rule: at least one `mediaList` item with ≥1
/// `localFilePaths` entry. Keys are optional (UI / associate later).
pub fn is_minimally_playable(doc: &NoudataDocument) -> bool {
    doc.media_list.iter().any(|item| {
        item.local_file_paths
            .as_ref()
            .is_some_and(|paths| paths.iter().any(|p| !p.is_empty()))
    })
}

/// Dynamic playlist: `searchString` present AND `mediaList` empty.
pub fn is_dynamic_playlist(doc: &NoudataDocument) -> bool {
    doc.media_list.is_empty()
        && doc
            .local_playback_data
            .as_ref()
            .and_then(|l| l.search_string.as_deref())
            .is_some_and(|s| !s.is_empty())
}

/// A titled playlist the user created (`createdByUser` set) whose `mediaList` has no usable
/// entry yet — e.g. a new playlist, or one whose last track was removed. It is indexed (as
/// a playlist with zero items) so it does not vanish from the lists; any other file without
/// a playable entry is still ignored (§3.1).
pub fn is_empty_user_playlist(doc: &NoudataDocument) -> bool {
    doc.release_data.is_none()
        && doc
            .refer_to_release_noudata
            .as_deref()
            .is_none_or(str::is_empty)
        && !is_minimally_playable(doc)
        && doc
            .playable_item_title
            .as_deref()
            .is_some_and(|t| !t.trim().is_empty())
        && doc
            .local_playback_data
            .as_ref()
            .and_then(|l| l.user_notes.as_ref())
            .and_then(|u| u.created_by_user.as_deref())
            .is_some_and(|u| !u.is_empty())
}

/// Outcome of [`classify_type`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TypeClassification {
    /// The type the document is treated as.
    pub ty: NoudataType,
    /// `true` when `ty` is the (valid) declared `noudataType`; `false` when it was inferred
    /// (omitted, unknown value, or an invalid combination).
    pub declared: bool,
    /// Why a declared type was ignored, plus soft problems (e.g. a dangling
    /// `referToReleaseNoudata`). Shown when editing metadata; never blocks playback.
    pub warnings: Vec<NoudataWarning>,
}

/// Effective type per the v0.4.0 `noudataType` rules. `resolve_release` maps a
/// `referToReleaseNoudata` relative path to the parsed referred document (`None` if
/// missing/unreadable); it is only called when needed.
///
/// - a valid declared type wins (even if it has a forbidden `releaseData`: preserved);
/// - an invalid combination (release without `releaseData`; looseTrack/linkTrack with an item
///   count other than one; linkTrack without `referToReleaseNoudata`) is ignored with a warning;
/// - omitted / unknown ⇒ §4.9: valid `releaseData` ⇒ release; `referToReleaseNoudata` to a
///   valid release ⇒ linkTrack; else userPlaylist (dynamic playlists included).
pub fn classify_type(
    doc: &NoudataDocument,
    resolve_release: impl FnOnce(&str) -> Option<NoudataDocument>,
) -> TypeClassification {
    let mut warnings = Vec::new();
    if let Some(declared) = doc.noudata_type {
        let n = doc.media_list.len();
        let problem = match declared {
            NoudataType::Release if doc.release_data.is_none() => {
                Some("release without releaseData")
            }
            NoudataType::LooseTrack | NoudataType::LinkTrack if n != 1 => {
                Some("a looseTrack/linkTrack needs exactly one mediaList item")
            }
            NoudataType::LinkTrack if !doc.has_refer() => {
                Some("linkTrack without referToReleaseNoudata")
            }
            _ => None,
        };
        match problem {
            None => {
                return TypeClassification {
                    ty: declared,
                    declared: true,
                    warnings,
                }
            }
            Some(why) => warn(
                &mut warnings,
                "noudataType",
                format!("declared type {} ignored: {why}", declared.as_str()),
            ),
        }
    }
    let ty = if doc.release_data.is_some() {
        NoudataType::Release
    } else if doc.has_refer()
        && doc
            .refer_to_release_noudata
            .as_deref()
            .and_then(resolve_release)
            .is_some_and(|d| d.release_data.is_some())
    {
        NoudataType::LinkTrack
    } else {
        NoudataType::UserPlaylist
    };
    TypeClassification {
        ty,
        declared: false,
        warnings,
    }
}

/// [`classify_type`] without the details.
pub fn effective_type(
    doc: &NoudataDocument,
    resolve_release: impl FnOnce(&str) -> Option<NoudataDocument>,
) -> NoudataType {
    classify_type(doc, resolve_release).ty
}

/// `userPlaylist` (dynamic included).
pub fn is_playlist(
    doc: &NoudataDocument,
    resolve_release: impl FnOnce(&str) -> Option<NoudataDocument>,
) -> bool {
    effective_type(doc, resolve_release) == NoudataType::UserPlaylist
}

/// Largest `.noudata` read from disk (bytes). A file on someone else's stick can be any size;
/// real documents (thousands of tracks with cues) stay far below this (`SECFIX_05` measured
/// a 20,000-item playlist and a 2,000-cue audiobook; see the work package decision log).
pub const MAX_LOCAL_NOUDATA_BYTES: u64 = 8 * 1024 * 1024;

/// Structural limits applied to a local `.noudata` before it is parsed (PAR-05): the depth
/// of a fetched document, but a much larger element budget. `serde_json::Value` costs
/// roughly 16-32 bytes per array element, so without a guard an 8 MiB `[0,0,0,...]` would
/// become hundreds of MB of RAM.
pub const MAX_LOCAL_NOUDATA_ELEMENTS: usize = 200_000;

/// Read a `.noudata` from disk as a hardened input (`SECFIX_05`): refuses (`InvalidData`)
/// a symlink, FIFO, device or directory (it never blocks), a file larger than
/// [`MAX_LOCAL_NOUDATA_BYTES`] without loading it, and a document that breaks the structural
/// guard ([`MAX_LOCAL_NOUDATA_ELEMENTS`], depth 32).
pub fn read_noudata_capped(path: &Path) -> std::io::Result<Vec<u8>> {
    let bytes = plippa_core::safe_fs::read_regular_capped(path, MAX_LOCAL_NOUDATA_BYTES)?;
    use crate::json_guard::{check_json_object_limits_with, JsonLimitError, MAX_JSON_DEPTH};
    match check_json_object_limits_with(&bytes, MAX_JSON_DEPTH, MAX_LOCAL_NOUDATA_ELEMENTS) {
        // Not-JSON / not-an-object is the parser's call (it names the problem in the scan
        // warnings); only the resource limits are refused here.
        Err(e @ (JsonLimitError::TooDeep | JsonLimitError::TooManyElements)) => Err(
            std::io::Error::new(std::io::ErrorKind::InvalidData, e.to_string()),
        ),
        _ => Ok(bytes),
    }
}

/// Resolver for [`classify_type`]/[`is_playlist`] that reads `refer` relative to the
/// directory of the `.noudata` at `noudata_path`.
pub fn fs_release_resolver(noudata_path: &Path) -> impl Fn(&str) -> Option<NoudataDocument> {
    let dir = noudata_path
        .parent()
        .map(Path::to_path_buf)
        .unwrap_or_default();
    move |rel: &str| {
        let bytes = read_noudata_capped(&dir.join(rel)).ok()?;
        parse_noudata(&bytes).ok()
    }
}
