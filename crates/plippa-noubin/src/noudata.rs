/// Parse `.noudata` JSON from bytes. Unknown fields are retained; unknown enum-like
/// strings and invalid elements never fail the parse (see
/// [`parse_noudata_with_warnings`] to see what was ignored).
pub fn parse_noudata(bytes: &[u8]) -> Result<NoudataDocument, NoudataError> {
    parse_noudata_with_warnings(bytes).map(|(doc, _)| doc)
}

/// Parse `.noudata` JSON from a string.
pub fn parse_noudata_str(s: &str) -> Result<NoudataDocument, NoudataError> {
    parse_noudata(s.as_bytes())
}

/// Like [`parse_noudata`], also returning per-element warnings. Accepts UTF-8 with or
/// without a BOM.
pub fn parse_noudata_with_warnings(
    bytes: &[u8],
) -> Result<(NoudataDocument, Vec<NoudataWarning>), NoudataError> {
    let bytes = bytes.strip_prefix(b"\xEF\xBB\xBF").unwrap_or(bytes);
    let value: Value = serde_json::from_slice(bytes)?;
    let Value::Object(map) = value else {
        return Err(NoudataError::NotObject);
    };
    let mut w = Vec::new();
    let doc = parse_root(map, &mut w);
    Ok((doc, w))
}

fn parse_root(mut m: Map<String, Value>, w: &mut Warnings) -> NoudataDocument {
    let path = "$";
    let what_am_i_looking_at = take_string(&mut m, "_whatAmILookingAt", path, w);
    let noudata_version = take_string(&mut m, "noudataVersion", path, w);
    let noudata_type = take_enum(&mut m, "noudataType", path, w, NoudataType::parse_known);
    let noubin_key = take_string(&mut m, "noubinKey", path, w);
    let noubin_key_normalised = take_string(&mut m, "noubinKeyNormalised", path, w);
    let playable_item_title = take_string(&mut m, "playableItemTitle", path, w);
    let playable_item_folder_safe_title =
        take_string(&mut m, "playableItemFolderSafeTitle", path, w);
    let playable_item_url_safe_title = take_string(&mut m, "playableItemURLSafeTitle", path, w);
    let playable_item_profile = take_enum(
        &mut m,
        "playableItemProfile",
        path,
        w,
        PlayableItemProfile::parse_known,
    );
    let refer_to_release_noudata = take_string(&mut m, "referToReleaseNoudata", path, w);

    let release_data = take_object(&mut m, "releaseData", path, w)
        .map(|o| ReleaseData::from_map(o, "releaseData", w));
    let local_playback_data = take_object(&mut m, "localPlaybackData", path, w)
        .map(|o| LocalPlaybackData::from_map(o, "localPlaybackData", w));

    // `mediaList` is always emitted, so a wrong-typed value is dropped (not preserved).
    let media_list = match m.remove("mediaList") {
        Some(Value::Array(items)) => items
            .into_iter()
            .enumerate()
            .filter_map(|(i, item)| {
                let p = format!("mediaList[{i}]");
                match item {
                    Value::Object(o) => Some(MediaListItem::from_map(o, &p, w)),
                    _ => {
                        warn(w, &p, "expected an object; element ignored");
                        None
                    }
                }
            })
            .collect(),
        Some(Value::Null) | None => Vec::new(),
        Some(_) => {
            warn(w, "mediaList", "expected an array; ignored");
            Vec::new()
        }
    };

    let dynamic = local_playback_data
        .as_ref()
        .is_some_and(|l| l.search_string.is_some());
    if media_list.is_empty() && !dynamic {
        warn(
            w,
            "mediaList",
            "missing or empty (and no searchString); file will not be playable",
        );
    }

    NoudataDocument {
        what_am_i_looking_at,
        noudata_version,
        noudata_type,
        noubin_key,
        noubin_key_normalised,
        playable_item_title,
        playable_item_folder_safe_title,
        playable_item_url_safe_title,
        playable_item_profile,
        refer_to_release_noudata,
        release_data,
        local_playback_data,
        media_list,
        extra: m,
    }
}

