//! Local `.noudata` document types and forward-compatible parse/write.
//!
//! The typed subset lives in [`crate::noudata_types`]; anything not typed is preserved
//! in the flattened `extra` maps so write-through never loses unknown data.

use crate::error::NoudataError;
use crate::noudata_types::{
    take_elements, take_enum, take_object, take_string, warn, CoverImage, Credits, CueList,
    ItemLocalPlaybackData, LocalPlaybackData, NoudataType, NoudataWarning, PlayableItemProfile,
    PrimaryArtist, ReleaseData, UniteData, UserNotes, Warnings,
};
use serde::Serialize;
use serde_json::{Map, Value};
use std::path::Path;

/// Value written to `_whatAmILookingAt` when a writer has to add it.
pub const WHAT_AM_I_LOOKING_AT: &str =
    "This is a noudata file from the Noubin standard. See https://github.com/TobyKLight/Noubin";

/// Value written to `noudataVersion` when a writer has to add it.
pub const NOUDATA_VERSION: &str = "0.4.0";

/// Root `.noudata` document (typed subset + preserved unknowns).
///
/// Field order is the write order, so `_whatAmILookingAt` is always the first key.
#[derive(Debug, Clone, PartialEq, Serialize, Default)]
pub struct NoudataDocument {
    #[serde(rename = "_whatAmILookingAt", skip_serializing_if = "Option::is_none")]
    pub what_am_i_looking_at: Option<String>,

    #[serde(rename = "noudataVersion", skip_serializing_if = "Option::is_none")]
    pub noudata_version: Option<String>,

    /// Declared type (v0.4.0). An unknown value stays in `extra` (and is written back);
    /// use [`classify_type`] for the effective type.
    #[serde(rename = "noudataType", skip_serializing_if = "Option::is_none")]
    pub noudata_type: Option<NoudataType>,

    #[serde(rename = "noubinKey", skip_serializing_if = "Option::is_none")]
    pub noubin_key: Option<String>,

    #[serde(
        rename = "noubinKeyNormalised",
        skip_serializing_if = "Option::is_none"
    )]
    pub noubin_key_normalised: Option<String>,

    #[serde(rename = "playableItemTitle", skip_serializing_if = "Option::is_none")]
    pub playable_item_title: Option<String>,

    #[serde(
        rename = "playableItemFolderSafeTitle",
        skip_serializing_if = "Option::is_none"
    )]
    pub playable_item_folder_safe_title: Option<String>,

    /// Preserved/edited but not generated by Plippa (linkhost concern).
    #[serde(
        rename = "playableItemURLSafeTitle",
        skip_serializing_if = "Option::is_none"
    )]
    pub playable_item_url_safe_title: Option<String>,

    /// Profile of this item (`release` / `looseTrack`); ignored for `userPlaylist`, omitted
    /// for `linkTrack` (inherited from the referred release). Missing/unknown ⇒ `other`.
    #[serde(
        rename = "playableItemProfile",
        skip_serializing_if = "Option::is_none"
    )]
    pub playable_item_profile: Option<PlayableItemProfile>,

    #[serde(
        rename = "referToReleaseNoudata",
        skip_serializing_if = "Option::is_none"
    )]
    pub refer_to_release_noudata: Option<String>,

    /// A `release` MUST have one; `userPlaylist`/`looseTrack`/`linkTrack` MUST NOT.
    #[serde(rename = "releaseData", skip_serializing_if = "Option::is_none")]
    pub release_data: Option<ReleaseData>,

    #[serde(rename = "localPlaybackData", skip_serializing_if = "Option::is_none")]
    pub local_playback_data: Option<LocalPlaybackData>,

    #[serde(rename = "mediaList")]
    pub media_list: Vec<MediaListItem>,

    /// Unknown root properties preserved for write-through.
    #[serde(flatten)]
    pub extra: Map<String, Value>,
}

/// One `mediaList` entry (typed subset + preserved unknowns such as `musicalData`).
#[derive(Debug, Clone, PartialEq, Serialize, Default)]
pub struct MediaListItem {
    #[serde(rename = "uniteData", skip_serializing_if = "Option::is_none")]
    pub unite_data: Option<UniteData>,

    #[serde(rename = "localFilePaths", skip_serializing_if = "Option::is_none")]
    pub local_file_paths: Option<Vec<String>>,

    #[serde(rename = "mediaTitle", skip_serializing_if = "Option::is_none")]
    pub media_title: Option<String>,

    #[serde(rename = "itemCredits", skip_serializing_if = "Option::is_none")]
    pub item_credits: Option<Credits>,

    #[serde(rename = "itemUserNotes", skip_serializing_if = "Option::is_none")]
    pub item_user_notes: Option<UserNotes>,

    #[serde(rename = "itemCoverImage", skip_serializing_if = "Option::is_none")]
    pub item_cover_image: Option<CoverImage>,

    #[serde(
        rename = "itemLocalPlaybackData",
        skip_serializing_if = "Option::is_none"
    )]
    pub item_local_playback_data: Option<ItemLocalPlaybackData>,

    #[serde(rename = "lyricsTranscript", skip_serializing_if = "Option::is_none")]
    pub lyrics_transcript: Option<String>,

    #[serde(rename = "cueLists", skip_serializing_if = "Vec::is_empty")]
    pub cue_lists: Vec<CueList>,

    #[serde(flatten)]
    pub extra: Map<String, Value>,
}

impl MediaListItem {
    fn from_map(mut m: Map<String, Value>, path: &str, w: &mut Warnings) -> Self {
        let local_file_paths =
            crate::noudata_types::take_string_array(&mut m, "localFilePaths", path, w);
        MediaListItem {
            unite_data: take_object(&mut m, "uniteData", path, w)
                .and_then(|o| UniteData::from_map(o, &format!("{path}.uniteData"), w)),
            local_file_paths,
            media_title: take_string(&mut m, "mediaTitle", path, w),
            item_credits: take_object(&mut m, "itemCredits", path, w)
                .map(|o| Credits::from_map(o, &format!("{path}.itemCredits"), w)),
            item_user_notes: take_object(&mut m, "itemUserNotes", path, w)
                .map(|o| UserNotes::from_map(o, &format!("{path}.itemUserNotes"), w)),
            item_cover_image: take_object(&mut m, "itemCoverImage", path, w)
                .and_then(|o| {
                    CoverImage::from_map_keep_empty(o, &format!("{path}.itemCoverImage"), w)
                }),
            item_local_playback_data: take_object(&mut m, "itemLocalPlaybackData", path, w).map(
                |o| ItemLocalPlaybackData::from_map(o, &format!("{path}.itemLocalPlaybackData"), w),
            ),
            lyrics_transcript: take_string(&mut m, "lyricsTranscript", path, w),
            cue_lists: take_elements(&mut m, "cueLists", path, w, CueList::from_map)
                .unwrap_or_default(),
            extra: m,
        }
    }
}

impl NoudataDocument {
    /// Set association keys (write-through helper for later NFC associate flows).
    pub fn set_noubin_keys(
        &mut self,
        noubin_key: impl Into<String>,
        normalised: impl Into<String>,
    ) {
        self.noubin_key = Some(noubin_key.into());
        self.noubin_key_normalised = Some(normalised.into());
    }

    /// Fill in what spec-conformant writers must set (`_whatAmILookingAt`,
    /// `noudataVersion`) and normalise multiline strings to LF (§1.22).
    pub fn prepare_for_write(&mut self) {
        self.what_am_i_looking_at
            .get_or_insert_with(|| WHAT_AM_I_LOOKING_AT.to_string());
        self.noudata_version
            .get_or_insert_with(|| NOUDATA_VERSION.to_string());
        // Writers always declare the type (an unknown future value already in `extra` is
        // kept as found, never overwritten or duplicated).
        if self.noudata_type.is_none() && !self.extra.contains_key("noudataType") {
            self.noudata_type = Some(self.infer_type_offline());
        }

        if let Some(rd) = self.release_data.as_mut() {
            lf_in_map(&mut rd.extra);
            if let Some(c) = rd.credits.as_mut() {
                lf_in_map(&mut c.extra);
            }
        }
        for item in &mut self.media_list {
            if let Some(t) = item.lyrics_transcript.as_mut() {
                lf(t);
            }
            for list in &mut item.cue_lists {
                for cue in &mut list.cues {
                    for span in &mut cue.cue_text_spans {
                        lf(&mut span.text);
                    }
                }
            }
        }
    }

    /// Serialise to pretty JSON suitable for writing a `.noudata` file
    /// (applies [`Self::prepare_for_write`] to a copy).
    pub fn to_json_pretty(&self) -> Result<String, NoudataError> {
        let mut doc = self.clone();
        doc.prepare_for_write();
        Ok(serde_json::to_string_pretty(&doc)?)
    }

    /// Write pretty JSON to `path` through the guarded temp-file + atomic-rename writer
    /// (same directory, fsync, unique temp name, permissions kept, symlinks and read-only
    /// files refused): a crash or power cut leaves the old or the new file, never a
    /// truncated one. No revision guard (last writer wins); callers that read first and
    /// must not clobber a concurrent edit use [`crate::write_noudata_atomic`] with a
    /// [`crate::WriteGuard`].
    pub fn write_to_path(&self, path: &Path) -> Result<(), crate::NoubinError> {
        crate::playlist::write_atomic_unguarded(self, path)
            .map(|_| ())
            .map_err(|e| match e {
                crate::playlist::AtomicWriteError::Io(e) => crate::NoubinError::Io(e),
                crate::playlist::AtomicWriteError::Noudata(e) => crate::NoubinError::Noudata(e),
                crate::playlist::AtomicWriteError::Conflict => crate::NoubinError::Io(
                    std::io::Error::other("the file changed underneath the write"),
                ),
            })
    }

    /// Root `playableItemProfile`, defaulting to `other`. For a `linkTrack` or `userPlaylist`
    /// the stored value is ignored by the standard — use [`Self::effective_profile`] there.
    ///
    /// Files written before standard v0.4.0 (including Plippa's own earlier imports) carry
    /// the profile as `releaseData.releaseProfile`; that is honoured when
    /// `playableItemProfile` is absent so they keep their Music / Mixes / ... place.
    pub fn profile(&self) -> PlayableItemProfile {
        self.playable_item_profile
            .or_else(|| {
                self.release_data
                    .as_ref()
                    .and_then(|r| r.extra.get("releaseProfile"))
                    .and_then(|v| v.as_str())
                    .and_then(PlayableItemProfile::parse_known)
            })
            .unwrap_or(PlayableItemProfile::Other)
    }

    /// The profile that applies to this item: `release`/`looseTrack` read the root
    /// property; `linkTrack` inherits from the referred release (via `resolve_release`);
    /// `userPlaylist` has none (`other`).
    pub fn effective_profile(
        &self,
        resolve_release: impl Fn(&str) -> Option<NoudataDocument>,
    ) -> PlayableItemProfile {
        match effective_type(self, &resolve_release) {
            NoudataType::Release | NoudataType::LooseTrack => self.profile(),
            NoudataType::UserPlaylist => PlayableItemProfile::Other,
            NoudataType::LinkTrack => self
                .refer_to_release_noudata
                .as_deref()
                .filter(|r| !r.is_empty())
                .and_then(resolve_release)
                .map_or(PlayableItemProfile::Other, |d| d.profile()),
        }
    }

    /// §4.9 inference that needs no file access: `releaseData` ⇒ release, a single item
    /// with `referToReleaseNoudata` ⇒ linkTrack (unverified), else userPlaylist.
    fn infer_type_offline(&self) -> NoudataType {
        if self.release_data.is_some() {
            NoudataType::Release
        } else if self.has_refer() && self.media_list.len() == 1 {
            NoudataType::LinkTrack
        } else {
            NoudataType::UserPlaylist
        }
    }

    pub(crate) fn has_refer(&self) -> bool {
        self.refer_to_release_noudata
            .as_deref()
            .is_some_and(|r| !r.is_empty())
    }

    /// The MUST / MUST NOT rules of the declared type (a document without a declared type
    /// is checked as its offline-inferred type). Empty when the document is valid.
    pub fn type_violations(&self) -> Vec<NoudataWarning> {
        let ty = self
            .noudata_type
            .unwrap_or_else(|| self.infer_type_offline());
        let mut v = Vec::new();
        let mut bad = |path: &str, msg: &str| {
            v.push(NoudataWarning {
                path: path.to_string(),
                message: msg.to_string(),
            })
        };
        let n = self.media_list.len();
        let has_item_credits = self.media_list.iter().any(|i| i.item_credits.is_some());
        match ty {
            NoudataType::Release => {
                if self.release_data.is_none() {
                    bad("releaseData", "a release must have releaseData");
                }
                if n == 0 {
                    bad("mediaList", "a release needs at least one item");
                }
            }
            NoudataType::UserPlaylist => {
                if self.release_data.is_some() {
                    bad("releaseData", "a userPlaylist must not have releaseData");
                }
                let dynamic = is_dynamic_playlist(self);
                if n == 0 && !dynamic && !is_empty_user_playlist(self) {
                    bad("mediaList", "a userPlaylist needs at least one item");
                }
            }
            NoudataType::LooseTrack | NoudataType::LinkTrack => {
                let name = ty.as_str();
                if n != 1 {
                    bad("mediaList", &format!("a {name} has exactly one item"));
                }
                if self.release_data.is_some() {
                    bad(
                        "releaseData",
                        &format!("a {name} must not have releaseData"),
                    );
                }
                if has_item_credits {
                    bad("mediaList", &format!("a {name} must not have itemCredits"));
                }
                if ty == NoudataType::LooseTrack && self.has_refer() {
                    bad(
                        "referToReleaseNoudata",
                        "a looseTrack must not have referToReleaseNoudata",
                    );
                }
                if ty == NoudataType::LinkTrack {
                    if !self.has_refer() {
                        bad(
                            "referToReleaseNoudata",
                            "a linkTrack requires referToReleaseNoudata",
                        );
                    }
                    if self.playable_item_profile.is_some() {
                        bad(
                            "playableItemProfile",
                            "a linkTrack omits playableItemProfile (inherited from the release)",
                        );
                    }
                }
            }
        }
        v
    }

    /// Serialise like [`Self::to_json_pretty`] but refuse a document that breaks its type's
    /// MUST/MUST NOT rules. Plippa's own creators use this for every *new* file; the plain
    /// writer stays lenient so foreign files keep unknown/extra data on rewrite (spec §3.1).
    pub fn to_json_pretty_checked(&self) -> Result<String, NoudataError> {
        let v = self.type_violations();
        if let Some(first) = v.first() {
            return Err(NoudataError::TypeRules(first.to_string()));
        }
        self.to_json_pretty()
    }

    /// Convert a `looseTrack` to a `release` in place (spec 1.31 / `noudataType`): adds the
    /// minimum `releaseData`, sets `noudataType` to `release`, keeps keys, notes, cues,
    /// `localPlaybackData` and the profile. `false` (nothing changed) for any other type.
    pub fn upgrade_loose_to_release(&mut self) -> bool {
        if self.noudata_type != Some(NoudataType::LooseTrack) {
            return false;
        }
        self.noudata_type = Some(NoudataType::Release);
        self.release_data.get_or_insert_with(ReleaseData::default);
        true
    }

    /// Set the release's primary artist (creating `credits`). Only for a document that has
    /// `releaseData` (upgrade a loose track first); `false` otherwise.
    pub fn set_release_primary_artist(&mut self, name: &str) -> bool {
        let Some(rd) = self.release_data.as_mut() else {
            return false;
        };
        let credits = rd.credits.get_or_insert_with(Credits::default);
        credits.primary_artists = Some(vec![PrimaryArtist {
            primary_artist_name: name.to_string(),
            extra: Default::default(),
        }]);
        credits.primary_artist_override_name = None;
        true
    }

    /// Display artist: override name, else primary artists joined with `, `.
    pub fn primary_artist_display(&self) -> Option<String> {
        self.release_data
            .as_ref()?
            .credits
            .as_ref()
            .and_then(Credits::primary_artist_display)
    }

    /// Cover image local filename by precedence. A `looseTrack` has no `releaseData`, so its
    /// item-0 `itemCoverImage` (which overrides all others per spec) comes first; otherwise
    /// the user's `localCoverImage`, then the release's `coverImage`. A present-but-empty
    /// `images` list in the winning user-level object means "no cover" (it hides the
    /// release's art instead of falling through to it).
    pub fn cover_local_filename(&self) -> Option<&str> {
        let item_cover = || {
            self.media_list
                .first()
                .and_then(|i| i.item_cover_image.as_ref())
        };
        if self.noudata_type == Some(NoudataType::LooseTrack) {
            if let Some(c) = item_cover() {
                if c.images.is_empty() {
                    return None;
                }
                if let Some(f) = c.primary_local_filename() {
                    return Some(f);
                }
            }
        }
        let local = self
            .local_playback_data
            .as_ref()
            .and_then(|l| l.local_cover_image.as_ref());
        if local.is_some_and(|c| c.images.is_empty()) {
            return None;
        }
        local
            .and_then(CoverImage::primary_local_filename)
            .or_else(|| {
                self.release_data
                    .as_ref()
                    .and_then(|r| r.cover_image.as_ref())
                    .and_then(CoverImage::primary_local_filename)
            })
    }
}

fn lf(s: &mut String) {
    if s.contains('\r') {
        *s = s.replace("\r\n", "\n").replace('\r', "\n");
    }
}

fn lf_in_map(m: &mut Map<String, Value>) {
    for key in ["description", "legalNotice", "additionalCreditsText"] {
        if let Some(Value::String(s)) = m.get_mut(key) {
            lf(s);
        }
    }
}

